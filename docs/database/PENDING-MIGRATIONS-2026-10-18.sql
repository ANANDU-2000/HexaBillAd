-- Four additive migrations for the live HexaBill database, in one idempotent script.
-- Run as the application role (hexabill_user) so the new tables are owned by it:
--   psql -1 -v ON_ERROR_STOP=1 -f PENDING-MIGRATIONS-2026-10-18.sql
-- Source: backend/HexaBill.Api/Migrations/20261018140000_AddRouteRuns.cs, ...150000_AddDriverLocationCurrent.cs,
--         ...160000_AddAiUsageDaily.cs, ...170000_AddTenantDocumentChunks.cs (this file is the same SQL; the C# files remain the source of truth).
-- Safe to run twice. Nothing is dropped or rewritten.

-- 20261018140000_AddRouteRuns
CREATE TABLE IF NOT EXISTS "RouteRuns" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "TenantId" integer NOT NULL,
    "RouteId" integer NOT NULL,
    "ServiceDate" timestamp with time zone NOT NULL,
    "StartedByUserId" integer NOT NULL,
    "StartedAt" timestamp with time zone NOT NULL,
    "EndedAt" timestamp with time zone NULL,
    "EndedByUserId" integer NULL,
    "EndNote" character varying(500) NULL,
    "StopsTotal" integer NOT NULL DEFAULT 0,
    "StopsDelivered" integer NOT NULL DEFAULT 0,
    "StopsFailed" integer NOT NULL DEFAULT 0,
    "StopsSkipped" integer NOT NULL DEFAULT 0,
    "StopsNotVisited" integer NOT NULL DEFAULT 0,
    CONSTRAINT "PK_RouteRuns" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RouteRuns_Routes_RouteId" FOREIGN KEY ("RouteId") REFERENCES "Routes" ("Id") ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS "IX_RouteRuns_TenantId_RouteId_ServiceDate" ON "RouteRuns" ("TenantId", "RouteId", "ServiceDate");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_RouteRuns_TenantId_RouteId" ON "RouteRuns" ("TenantId", "RouteId") WHERE "EndedAt" IS NULL;
CREATE INDEX IF NOT EXISTS "IX_RouteRuns_RouteId" ON "RouteRuns" ("RouteId");

-- 20261018150000_AddDriverLocationCurrent
CREATE TABLE IF NOT EXISTS "DriverLocationCurrents" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "TenantId" integer NOT NULL,
    "RouteId" integer NOT NULL,
    "UserId" integer NOT NULL,
    "RunId" integer NOT NULL,
    "SessionId" character varying(64) NOT NULL,
    "Latitude" numeric(9,6) NOT NULL,
    "Longitude" numeric(9,6) NOT NULL,
    "AccuracyMeters" numeric(8,1) NULL,
    "ConsentAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_DriverLocationCurrents" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_DriverLocationCurrents_TenantId_RouteId_UserId" ON "DriverLocationCurrents" ("TenantId", "RouteId", "UserId");
CREATE INDEX IF NOT EXISTS "IX_DriverLocationCurrents_RunId" ON "DriverLocationCurrents" ("RunId");

-- 20261018160000_AddAiUsageDaily
CREATE TABLE IF NOT EXISTS "AiUsageDaily" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "TenantId" integer NOT NULL,
    "Day" date NOT NULL,
    "Calls" integer NOT NULL DEFAULT 0,
    "Tokens" integer NOT NULL DEFAULT 0,
    "UpdatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_AiUsageDaily" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_AiUsageDaily_TenantId_Day" ON "AiUsageDaily" ("TenantId", "Day");

-- 20261018170000_AddTenantDocumentChunks
CREATE TABLE IF NOT EXISTS "TenantDocumentChunks" (
    "Id" uuid NOT NULL,
    "TenantId" integer NOT NULL,
    "DocumentId" uuid NOT NULL,
    "VersionId" uuid NOT NULL,
    "ChunkIndex" integer NOT NULL,
    "Location" character varying(40) NOT NULL,
    "Text" text NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_TenantDocumentChunks" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TenantDocumentChunks_TenantId_DocumentId_VersionId_ChunkIndex" ON "TenantDocumentChunks" ("TenantId", "DocumentId", "VersionId", "ChunkIndex");
CREATE INDEX IF NOT EXISTS "IX_TenantDocumentChunks_TenantId_VersionId" ON "TenantDocumentChunks" ("TenantId", "VersionId");
ALTER TABLE "TenantDocumentVersions" ADD COLUMN IF NOT EXISTS "SearchStatus" character varying(20) NOT NULL DEFAULT 'None';
ALTER TABLE "TenantDocumentVersions" ADD COLUMN IF NOT EXISTS "SearchNote" character varying(300) NULL;
ALTER TABLE "TenantDocumentVersions" ADD COLUMN IF NOT EXISTS "ChunkCount" integer NOT NULL DEFAULT 0;

