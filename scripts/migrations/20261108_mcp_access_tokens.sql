-- Company MCP access tokens (Settings -> AI -> MCP connections).
--
-- This used to be an EF migration. That was wrong for this deployment: production treats "any
-- pending migration" as NOT READY (see /health/ready + DatabaseInitializationStatus), so shipping
-- the migration without applying it made Render return 503 and the whole app showed
-- "Server unavailable".
--
-- Run this SQL once, as a normal backed-up release step, on the production database.
-- It is additive and idempotent; it does not touch existing tables.

CREATE TABLE IF NOT EXISTS "McpAccessTokens" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "TenantId" integer NOT NULL,
    "UserId" integer NOT NULL,
    "Name" character varying(80) NOT NULL,
    "TokenHash" character varying(64) NOT NULL,
    "TokenPrefix" character varying(16) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "ExpiresAt" timestamp with time zone NULL,
    "RevokedAt" timestamp with time zone NULL,
    "LastUsedAt" timestamp with time zone NULL,
    CONSTRAINT "PK_McpAccessTokens" PRIMARY KEY ("Id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_McpAccessTokens_TokenHash" ON "McpAccessTokens" ("TokenHash");
CREATE INDEX IF NOT EXISTS "IX_McpAccessTokens_TenantId_RevokedAt" ON "McpAccessTokens" ("TenantId", "RevokedAt");
